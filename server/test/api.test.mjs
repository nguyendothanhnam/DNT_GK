import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createStore } from '../store.mjs';
import { createApp } from '../app.mjs';
import { hashPassword, verifyPassword } from '../security.mjs';

test('CRUD, đăng nhập, phân quyền, băm mật khẩu và lưu dữ liệu bền vững', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'userspace-'));
  const file = join(dir, 'db.json');
  const store = createStore({ mode: 'local', file });
  await store.put({ email: 'admin@example.com', matkhau: hashPassword('Admin@123456'), hoten: 'Quản trị viên', hinhanh: '' });
  const server = createApp(store);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function request(path, method = 'GET', body, token) {
    const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json() };
  }
  assert.equal((await request('/users')).status, 401);
  assert.equal((await request('/login', 'POST', { email: 'admin@example.com', matkhau: 'wrong' })).status, 401);
  const login = await request('/login', 'POST', { email: ' ADMIN@example.com ', matkhau: 'Admin@123456' });
  assert.equal(login.status, 200); assert.equal(login.data.isAdmin, true);
  assert.equal('matkhau' in login.data.user, false);
  const token = login.data.token;
  // A separate login models a phone reading changes made by the web session.
  const phoneLogin = await request('/login', 'POST', { email: 'admin@example.com', matkhau: 'Admin@123456' });
  const phoneToken = phoneLogin.data.token;
  assert.notEqual(phoneToken, token);
  assert.equal((await request('/users', 'GET', undefined, phoneToken)).data.length, 1);
  const user = { email: 'student@example.com', matkhau: 'Student@123', hoten: 'Nguyễn Minh Anh', hinhanh: 'data:image/png;base64,aGVsbG8=' };
  assert.equal((await request('/users', 'POST', { ...user, role: 'admin' }, token)).status, 400);
  assert.equal((await request('/users', 'POST', { ...user, matkhau: '123' }, token)).status, 400);
  assert.equal((await request('/users', 'POST', { ...user, hinhanh: 'javascript:alert(1)' }, token)).status, 400);
  assert.equal((await request('/users', 'POST', user, token)).status, 201);
  assert.equal((await request('/users', 'GET', undefined, phoneToken)).data.find(u => u.email === user.email).hoten, user.hoten);
  const duplicate = await Promise.all([request('/users', 'POST', { ...user, email: 'parallel@example.com' }, token), request('/users', 'POST', { ...user, email: 'parallel@example.com' }, token)]);
  assert.deepEqual(duplicate.map(r => r.status).sort(), [201, 409]);
  assert.equal((await request('/users', 'POST', { ...user, email: 'STUDENT@example.com' }, token)).status, 409);
  const list = await request('/users', 'GET', undefined, token);
  assert.equal(list.data.length, 3); assert.ok(list.data.every(u => !('matkhau' in u)));
  const reloaded = createStore({ mode: 'local', file });
  const saved = await reloaded.get(user.email);
  assert.deepEqual(Object.keys(saved).sort(), ['email', 'hinhanh', 'hoten', 'matkhau']);
  assert.notEqual(saved.matkhau, user.matkhau); assert.ok(verifyPassword(user.matkhau, saved.matkhau));
  const member = await request('/login', 'POST', { email: user.email, matkhau: user.matkhau });
  assert.equal(member.data.isAdmin, false);
  assert.equal((await request('/users', 'GET', undefined, member.data.token)).status, 403);
  assert.equal((await request('/me', 'GET', undefined, member.data.token)).data.hinhanh, user.hinhanh);
  assert.equal((await request('/export', 'GET', undefined, member.data.token)).status, 403);
  const path = `/users/${encodeURIComponent(user.email)}`;
  assert.equal((await request(path, 'PUT', { ...user, email: 'other@example.com' }, token)).status, 400);
  const updatedImage = 'data:image/png;base64,bmV3LWltYWdl';
  assert.equal((await request(path, 'PUT', { ...user, hoten: 'Đã cập nhật', hinhanh: updatedImage, matkhau: '' }, token)).status, 200);
  const phoneUsers = (await request('/users', 'GET', undefined, phoneToken)).data;
  assert.equal(phoneUsers.find(u => u.email === user.email).hoten, 'Đã cập nhật');
  assert.equal(phoneUsers.find(u => u.email === user.email).hinhanh, updatedImage);
  const memberProfile = await request('/me', 'GET', undefined, member.data.token);
  assert.equal(memberProfile.data.hoten, 'Đã cập nhật');
  assert.equal(memberProfile.data.hinhanh, updatedImage);
  assert.ok(verifyPassword(user.matkhau, (await store.get(user.email)).matkhau));
  assert.equal((await request(path, 'PUT', { ...user, matkhau: 'NewPassword@123' }, token)).status, 200);
  assert.equal((await request('/me', 'GET', undefined, member.data.token)).status, 401);
  assert.equal((await request('/login', 'POST', { email: user.email, matkhau: user.matkhau })).status, 401);
  const newLogin = await request('/login', 'POST', { email: user.email, matkhau: 'NewPassword@123' });
  assert.equal(newLogin.status, 200);
  assert.equal((await request('/users/admin%40example.com', 'DELETE', undefined, token)).status, 400);
  assert.equal((await request(path, 'DELETE', undefined, token)).status, 200);
  assert.equal((await request('/users', 'GET', undefined, phoneToken)).data.some(u => u.email === user.email), false);
  assert.equal((await request('/me', 'GET', undefined, newLogin.data.token)).status, 401);
  assert.equal((await request(path, 'DELETE', undefined, token)).status, 404);
  const exported = await request('/export', 'GET', undefined, token);
  assert.deepEqual(Object.keys(exported.data), ['users']);
  assert.deepEqual(JSON.parse(await readFile(file, 'utf8')), exported.data);
  assert.equal((await request('/logout', 'POST', undefined, token)).status, 200);
  assert.equal((await request('/users', 'GET', undefined, token)).status, 401);
});
